"""Regenerate js/src/widgets/sample-digits.ts: one handwritten digit per class
for the twin's demos, chosen to suit the exported MNIST weights.

For each digit this looks at the images in the 10,000-image MNIST test set that
docs/mnist-weights.json answers correctly, keeps the half it answers by the
wider margin (the gap between the largest output and the runner-up, as a share
of the largest), and of those takes the one nearest the average image of that
digit. The samples are therefore ordinary-looking digits the network is sure
of, not a fair sample; its accuracy over the whole test set is what
scripts/slider_scale_sim.py reports. A digit the network never gets right is
left out.

Run with `uv run scripts/pick_sample_digits.py` after exporting new MNIST
weights, then rebuild and commit `js/dist/`.
"""

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import apparatus_sim as sim

HEADER = """// Generated by scripts/pick_sample_digits.py: for each digit, an ordinary-looking
// MNIST test image that the bundled weights answer correctly by a clear margin.

export interface SampleDigit {
  label: number;
  pixels: number[];
}

export const sampleDigits: SampleDigit[] = [
"""


def main() -> None:
    _, _, x, y = sim.mnist_data()
    weights = json.loads((sim.REPO / "docs/mnist-weights.json").read_text())
    outputs = sim.forward(np.array(weights["B"]), np.array(weights["D"]), x)
    ranked = np.sort(outputs, axis=1)
    margin = (ranked[:, -1] - ranked[:, -2]) / np.maximum(ranked[:, -1], 1e-9)
    correct = outputs.argmax(1) == y

    entries = []
    for digit in range(10):
        candidates = np.flatnonzero(correct & (y == digit))
        if len(candidates) == 0:
            print(f"{digit}: never answered correctly, left out")
            continue
        sure = candidates[margin[candidates] >= np.median(margin[candidates])]
        distance = np.linalg.norm(x[sure] - x[y == digit].mean(0), axis=1)
        best = sure[distance.argmin()]
        top = ", ".join(f"{v:.2f}" for v in ranked[best, :-3:-1])
        print(f"{digit}: test image {best}, largest outputs {top}")
        rows = "\n".join(
            "      " + ", ".join(f"{v:.3f}" for v in row) + ","
            for row in np.round(x[best], 3).reshape(6, 6)
        )
        entries.append(
            f"  {{\n    label: {digit},\n    pixels: [\n{rows}\n    ],\n  }},\n"
        )

    path = sim.REPO / "js/src/widgets/sample-digits.ts"
    path.write_text(HEADER + "".join(entries) + "];\n")


main()
